#1. Password hashing ################
# Passwords are never stored in plain text — only their SHA-256 hash is saved.
# Even if the database is exposed, nobody can recover the original passwords.

# \ Begin code generated by Claude Sonnet 4.6
def _hash(password: str) -> str:
    """
    Returns the SHA-256 hash of a password as a hex string.
    Used both when creating an account and when verifying login credentials —
    the stored hash is compared to the hash of the password the user types in.

    Parameters:
        password : str — the plain-text password to hash.

    Returns a 64-character hex string.
    """
    return hashlib.sha256(password.encode()).hexdigest()
