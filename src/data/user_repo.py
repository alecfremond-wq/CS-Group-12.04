"""
Data access layer for user accounts and profiles.
Handles account creation, login verification, profile read/write and deletion.
Every function that touches a specific profile takes an explicit user_id so that
pantry and meal-plan data (which already carry user_id foreign keys) stays
properly scoped per person.

Dependencies:

  - hashlib (stdlib)  : SHA-256 password hashing — passwords are never stored in plain text.
  - typing (stdlib)   : Optional — type hints.

  - src.data.database
      query_df(sql, params) -> executes a SELECT and returns a DataFrame
                               (or None if no rows / table missing).
      execute(sql, params)  -> executes INSERT / DELETE / UPDATE statements.

Database tables:

  users : one row per user. Stores name, username, hashed password, diet,
          allergies (comma-separated string), and skill level.
          Primary key `id` is used as foreign key in pantry and meal_plan tables.

Author: Alec Frémond

Sources: Claude Sonnet 4.6 (see comments below)

"""

