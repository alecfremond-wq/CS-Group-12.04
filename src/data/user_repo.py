#3. Profile read / write ####
# Functions to save and load the user's profile (diet, allergies, skill level).

def save_profile(profile: dict, user_id: Optional[int] = None) -> int:
    """
    Persists a user profile and returns its database id.
    If user_id is given, updates that row. If None, inserts a new one.

    Parameters:
        profile : dict          — contains name, diet, allergies, skill_level.
        user_id : int or None   — if given, updates that row; if None, inserts a new one.

    Returns the integer id of the saved row.
    """
    # same allergies serialization as in create_account — list to comma-separated string
    allergies = profile.get("allergies", [])
    if isinstance(allergies, list):
        allergies_str = ",".join(allergies)
    else:
        allergies_str = str(allergies or "")

    values = (
        profile.get("name", ""),
        profile.get("diet", "omnivore"),
        allergies_str,
        profile.get("skill_level", "beginner"),
    )

    if user_id is not None:
        # update the existing row — keeps the same id so all foreign keys stay valid
        execute(
            "UPDATE users "
            "SET name=?, diet=?, allergies=?, skill_level=? "
            "WHERE id=?",
            values + (user_id,),
        )
        return user_id

    # no user_id provided — insert a new row
    execute(
        "INSERT INTO users (name, diet, allergies, skill_level) "
        "VALUES (?, ?, ?, ?)",
        values,
    )
    # retrieve the id of the row we just inserted (last inserted row has the highest id)
    df = query_df("SELECT id FROM users ORDER BY id DESC LIMIT 1")
    return int(df.iloc[0]["id"])


def load_profile(user_id: int) -> Optional[dict]:
    """
    Loads a user's profile from the database by their id.
    Returns a dict matching the shape of st.session_state["user_profile"],
    or None if no user with that id exists.

    Parameters:
        user_id : int — the logged-in user's database ID.
    """
    df = query_df("SELECT * FROM users WHERE id = ?", (user_id,))
    if df.empty:
        return None

    row = df.iloc[0]
    # parse the comma-separated allergies string back into a Python list
    raw_allergies = row["allergies"] or ""
    allergies = [a.strip() for a in raw_allergies.split(",") if a.strip()]

    return {
        "name": row["name"] or "",
        "diet": row["diet"] or "omnivore",
        "allergies": allergies,
        "skill_level": row["skill_level"] or "beginner",
    }


#4. Utility ##
# Helper functions for loading all profiles and deleting an account.

def load_all_profiles() -> list[dict]:
    """
    Returns a list of {id, name} for every user in the database.
    Used to display a profile-selection screen.
    """
    df = query_df("SELECT id, name FROM users ORDER BY id ASC")
    if df.empty:
        return []
    return df.to_dict("records")


def delete_profile(user_id: int) -> None:
    """
    Deletes the user row. SQLite CASCADE automatically removes
    all their pantry items and meal plan entries as well.

    Parameters:
        user_id : int — the id of the user to delete.
    """
    execute("DELETE FROM users WHERE id = ?", (user_id,))
