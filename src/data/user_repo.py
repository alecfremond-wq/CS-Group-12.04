#2. Account management ##########
# Functions to create accounts and verify login credentials.

# \ Begin code generated by Claude Sonnet 4.6
def create_account(profile: dict, username: str, password: str) -> int:
    """
    Creates a new user row in the database and returns the new user_id.
    Raises ValueError if the username is already taken (enforced by UNIQUE index).

    Parameters:
        profile  : dict — contains name, diet, allergies, skill_level.
        username : str  — the chosen username (will be lowercased).
        password : str  — the plain-text password (will be hashed before storage).

    Returns the integer id of the newly created row.
    """
    username = username.strip().lower()

    # check if the username already exists before trying to insert
    taken = query_df("SELECT id FROM users WHERE username = ?", (username,))
    if not taken.empty:
        raise ValueError("This username is already taken.")

    # SQLite doesn't support Python lists — allergies must be serialized to a
    # comma-separated string for storage, then parsed back to a list when loading.
    # e.g. ["Gluten", "Nuts"] → "gluten,nuts" on save, "gluten,nuts" → ["Gluten", "Nuts"] on load
    allergies = profile.get("allergies", [])
    allergies_str = ",".join(allergies) if isinstance(allergies, list) else str(allergies or "")

    execute(
        "INSERT INTO users (name, username, password_hash, diet, allergies, skill_level) "
        "VALUES (?, ?, ?, ?, ?, ?)",
        (
            profile.get("name", ""),
            username,
            _hash(password),
            profile.get("diet", "omnivore"),
            allergies_str,
            profile.get("skill_level", "beginner"),
        ),
    )
    # retrieve the id of the row we just inserted
    df = query_df("SELECT id FROM users WHERE username = ?", (username,))
    return int(df.iloc[0]["id"])


def check_login(username: str, password: str) -> Optional[int]:
    """
    Verifies login credentials by hashing the given password and comparing
    it to the stored hash.

    Parameters:
        username : str — the username entered by the user.
        password : str — the plain-text password entered by the user.

    Returns the user_id if credentials match, or None if they don't.
    """
    df = query_df(
        "SELECT id FROM users WHERE username = ? AND password_hash = ?",
        (username.strip().lower(), _hash(password)),
    )
    return int(df.iloc[0]["id"]) if not df.empty else None
